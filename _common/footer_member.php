<script>
// Check authentication status and update header button
function updateAuthButton() {
    var authToken = localStorage.getItem('auth_token');
    var container = document.getElementById('auth_button_container');
    
    if (container) {
        if (authToken && authToken !== '' && authToken !== 'null') {
            // User is logged in
            container.innerHTML = '<a href="profile" class="site-button" style="background-color: #28a745; color: white;">My Profile</a>' +
                '<a onclick="logout_user()" class="site-button" style="background-color: red; color: white; margin-left: 10px; cursor: pointer;">Logout</a>';
        } else {
            // User is not logged in
            container.innerHTML = '<a href="login" class="site-button">Member Login</a>' +
                '<a href="register" class="site-button" style="margin-left: 10px;">REGISTER TO JOIN US</a>';
        }
    }
}

// Logout user function
function logout_user() {
    if (confirm('Are you sure you want to logout?')) {
        localStorage.clear();
        // Redirect to home/login
        window.location.href = 'index';
    }
}

// Update auth button on page load
document.addEventListener('DOMContentLoaded', updateAuthButton);

// Also update if localStorage changes (in another tab)
window.addEventListener('storage', updateAuthButton);
</script>

