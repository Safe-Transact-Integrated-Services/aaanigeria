<script>
(function() {
    var params = new URLSearchParams(window.location.search);
    var message = params.get("admin_action_message");
    var status = params.get("admin_action_status");

    if (!message) {
        return;
    }

    var icon = "info";
    if (status === "approved" || status === "denied") {
        icon = "success";
    } else if (status === "already-approved") {
        icon = "success";
    } else if (status === "already-denied") {
        icon = "info";
    } else if (status === "error") {
        icon = "error";
    }

    if (window.Swal) {
        Swal.fire({
            text: message,
            icon: icon,
            confirmButtonText: "OK"
        }).then(function() {
            params.delete("admin_action_message");
            params.delete("admin_action_status");
            var nextQuery = params.toString();
            var nextUrl = window.location.pathname + (nextQuery ? "?" + nextQuery : "") + window.location.hash;
            window.history.replaceState({}, document.title, nextUrl);
        });
    } else {
        window.alert(message);
    }
})();
</script>
